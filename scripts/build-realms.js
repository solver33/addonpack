#!/usr/bin/env node
// Builds extension/lib/realms.js from LibRealmInfo.lua (https://github.com/phanx-wow/LibRealmInfo, zlib license).
// Usage: node scripts/build-realms.js path/to/LibRealmInfo.lua
'use strict';
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) {
  console.error('Usage: node scripts/build-realms.js path/to/LibRealmInfo.lua');
  process.exit(1);
}

const REGIONS = new Set(['EU', 'US', 'KR', 'TW']); // regions raider.io supports
const byName = new Map();

for (const m of fs.readFileSync(src, 'utf8').matchAll(/^\[\d+\]="([^"]+)"/gm)) {
  const [name, , locale, region, extra] = m[1].split(',');
  if (!REGIONS.has(region)) continue;
  // For non-US realms the 5th field is the English name (US realms have a timezone there).
  const english = region !== 'US' && extra && extra !== name ? extra : null;
  const entry = byName.get(name) || { name, english, locale, regions: [] };
  if (!entry.regions.includes(region)) entry.regions.push(region);
  byName.set(name, entry);
}

const rows = [...byName.values()]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((r) => [r.name, r.english, r.regions.sort().join(',')]);

const out = `// Generated by scripts/build-realms.js from LibRealmInfo (zlib license, (c) Phanx). Do not edit by hand.
// Each row: [realm name, English name or null, regions]
(function (root) {
  'use strict';
  const REALMS = ${JSON.stringify(rows).replace(/\],\[/g, '],\n    [')};
  if (typeof module !== 'undefined' && module.exports) module.exports = REALMS;
  else root.SOLVER33_REALMS = REALMS;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
fs.writeFileSync(path.join(__dirname, '..', 'extension', 'lib', 'realms.js'), out);
console.log(`Wrote ${rows.length} realms`);
